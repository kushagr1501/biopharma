								<p> <strong>India, Hyderabad, 17th December 2019:</strong>  Hetero, one of India’s leading generic pharmaceutical companies and the world’s largest producer of antiretroviral drugs, today announces the launch of the latest 3-in-1 antiretroviral combination drug under the brand name ‘TAFFIC’ in India. The product ‘TAFFIC’ is the generic version of Gilead’s Biktarvy® and has been approved by the Drug Controller General of India (DCGI). The product will be marketed and distributed by Hetero Healthcare Ltd. in India.

