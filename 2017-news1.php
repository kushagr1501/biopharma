								<p> <strong>India, Hyderabad, 14th November 2017:</strong> Hetero, one of India’s leading generic pharmaceutical companies and one of the world’s largest producer of anti-retroviral drugs, today announced that it has received the approval from Drug Controller General of India (DCGI) to launch the first-ever generic fixed-dose combination (FDC) drug ‘Darunavir + Ritonavir’ in India. The product will be marketed and distributed under the brand name ‘DANAVIR-R’ in India by Hetero Healthcare Ltd. It will be made available in three strengths - 800/100mg, 600/100mg and 400/50mg</p>
