<p>~The product will be available under the brand name ‘Ledifos’ in India~</p>
								<p>  <strong>India, Hyderabad, December 8th, 2015:</strong> Hetero, one of India’s leading generic pharmaceutical companies and one of the world’s largest producer of anti-retroviral drugs, today announced that it is the first company in India to receive the approval for the fixed-dose combination Ledipasvir-Sofosbuvir (90mg/400mg) from Drug Controller General of India (DCGI). Following the non-exclusive licensing agreement signed with Gilead Sciences in September last year, to manufacture and market chronic hepatitis C medicines, Hetero is all set to launch the fixed-dose combination therapy ‘Ledipasvir-Sofosbuvir’ for the Indian patients. The product will be available under the brand name ‘Ledifos’ in India.
</p>
								<p>This fixed-dose combination is the generic version of Gilead’s brand Harvoni, approved by US FDA for the treatment of chronic hepatitis genotype 1 in both treatment –naïve and treatmentexperienced patients. Sofosbuvir in combination with Ledipasvir has shown to have high cure rates of around 90%.,1
</p>
<p>Hepatitis C is a growing public health concern, particularly in developing countries. In India alone, it is estimated that 12-18 million patients are infected with Hepatitis C which is several fold greater than those with HIV/AIDS. Untreated chronic hepatitis C increases the risk of cirrhosis of liver, liver failure and hepatocellular carcinoma.</p>
<p> <strong>Dr BPS Reddy, CMD, Hetero group of companies commented:</strong> “We have been the frontrunners in launching the generic Sofosbuvir in several countries. We are now happy to extend the fixed-dose combination therapy ‘Ledipasvir-Sofosbuvir (Ledifos) to Indian patients, which is much more effective than Sofosbuvir. With the launch of Ledisof, we look forward in bringing a paradigm shift in Hepatitis C management in the country.”
</p>
							
