              <p> <strong>India, Hyderabad, 13th May 2020:</strong> Hetero, one of India’s leading generic pharmaceutical companies and the world’s largest producer of anti-retroviral drugs, announced today that it has entered into a licensing agreement with Gilead Sciences, Inc. for the manufacturing and distribution of ‘Remdesivir’ for the treatment of Covid-19. Under this licensing deal, Hetero will be supplying Remdesivir in 127 countries, including India, subject to regulatory approvals in respective countries.
</p>
				<p> <strong> Dr. B. Partha Saradhi Reddy, Chairman, Hetero Group of Companies, commented:</strong> “Hetero is pleased to partner with Gilead to enable access for this important drug to India and other developing countries at this crucial time. This agreement also illustrates the significance of global collaboration and the need for coming together to fight the health crises impacting humanity. Hetero has developed this product in India and has already been working with the government, ICMR, and DCGI for necessary studies and approvals to bring this product to treat COVID-19 patients in India.”
</p>
				<p>Remdesivir will be manufactured in our formulation facility in Hyderabad, India, which has been approved by stringent global regulatory authorities such as USFDA and EU, among others. Hetero has developed the fully vertically integrated supply chain for this product complementing the ‘Make in India’ campaign as defined by our Hon’ble Prime Minister.
</p>
<strong>Important Information about Remdesivir</strong>
				<p>U.S. Food and Drug Administration (FDA) has granted emergency use authorization (EUA) for the investigational antiviral remdesivir to treat COVID-19. Remdesivir is authorized for the treatment of hospitalized patients with severe COVID-19 disease. The optimal duration of treatment is still being studied in ongoing clinical trials. Under the EUA, both 5-day and 10-day treatment durations are suggested, based on the severity of disease. The authorization is temporary and does not take the place of the formal new drug application submission, review and approval process. The EUA allows for the distribution and emergency use of remdesivir only for the treatment of COVID-19; Remdesivir remains an investigational drug and is not approved anywhere globally including US & India.
</p>
