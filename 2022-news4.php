								<p> <strong>India, Hyderabad; 21 March, 2022:</strong>  Hetero, a globally renowned vertically integrated pharmaceutical organization announced today that its biologics arm ‘Hetero Biopharma’ has received approval from the Central Drugs Standard Control Organisation (CDSCO) to manufacture for sale, Sputnik Light, with restricted emergency use in India. Hetero is the first biopharmaceutical company in India to receive manufacturing & marketing (M&M) approval for the product manufactured locally for the prevention of COVID-19 in adults aged over 18 years, administered in single dose of 0.5ml. All other currently approved vaccines in India require two doses of administration.</p>
